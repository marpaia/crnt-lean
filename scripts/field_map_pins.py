#!/usr/bin/env python3
"""Generate `test/FieldMapAudit.lean` from `docs/field-map.md`.

Every declaration named in the *Lean* column of the leaf tables of `docs/field-map.md` is
probed with `#print axioms`.  The script fails if a name does not resolve or if its axiom set
is not a subset of `[propext, Classical.choice, Quot.sound]`; otherwise it writes the test file
with each output pinned by `#guard_msgs`, so the test fails if a declaration is renamed,
removed, or acquires `sorryAx`.

Usage
    python3 scripts/field_map_pins.py            # probe with `lean` and write the test
    python3 scripts/field_map_pins.py --list     # print the extracted names and exit

Requires `lean` on PATH and `LEAN_PATH` set to a tree in which `CRNT` and `CRNTFrontier`
are built.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, "docs", "field-map.md")
OUT = os.path.join(ROOT, "test", "FieldMapAudit.lean")
ALLOWED = {"propext", "Classical.choice", "Quot.sound"}
IMPORTS = ["CRNT", "CRNTFrontier"]
NAME = re.compile(r"`([A-Za-z_][\w.']*)`")


def extract() -> list[tuple[str, str]]:
    """(leaf id, declaration) pairs from the Lean column of every leaf table."""
    pairs = []
    for line in open(MAP, encoding="utf-8"):
        if not line.startswith("|"):
            continue
        cols = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cols) < 5 or not re.fullmatch(r"[A-Z]\d+", cols[0]):
            continue
        for name in NAME.findall(cols[3]):
            pairs.append((cols[0], name))
    return pairs


def probe(names: list[str]) -> dict[str, str]:
    """Run `#print axioms` on every name; return name -> message text."""
    with tempfile.NamedTemporaryFile("w", suffix=".lean", dir=ROOT, delete=False) as fh:
        for imp in IMPORTS:
            fh.write(f"import {imp}\n")
        for n in names:
            fh.write(f"#print axioms {n}\n")
        path = fh.name
    try:
        res = subprocess.run(["lean", path], cwd=ROOT, capture_output=True, text=True)
    finally:
        os.unlink(path)
    out = res.stdout + res.stderr
    msgs: dict[str, str] = {}
    # Lean prints one block per declaration:  'NAME' depends on axioms: [...]
    # The axiom list may be wrapped over several lines, and the *name* may itself
    # end in a prime (`foo'`), in which case Lean prints `'foo''`.  So the name
    # is recovered by walking back from the message to the quoted name.
    msg_re = re.compile(r"(depends on axioms: \[[^\]]*\]|does not depend on any axioms)", re.S)
    for m in msg_re.finditer(out):
        head = out[:m.start()]
        j = head.rfind("'")
        if j < 0:
            continue
        if j >= 1 and head[j - 1] == "'":
            i = head.rfind("'", 0, j - 1)   # 'NAME'' : the name ends in a prime
        else:
            i = head.rfind("'", 0, j)        # 'NAME'
        if i < 0:
            continue
        name = head[i + 1:j]
        # The quoted name and the axiom clause are two separate pieces of Lean's
        # output; they must be joined by a space, or the generated `#guard_msgs`
        # docstring reads `'NAME'depends on axioms: [...]` and the test fails to
        # elaborate with "Docstring on `#guard_msgs` does not match generated message".
        msgs[name] = " ".join((head[i:j + 1] + " " + m.group(0)).split())
    errors = [l for l in out.splitlines() if ": error" in l]
    if errors:
        print("\n".join(errors[:20]), file=sys.stderr)
    return msgs


def main() -> int:
    pairs = extract()
    if "--list" in sys.argv:
        for leaf, n in pairs:
            print(f"{leaf}\t{n}")
        return 0
    names = list(dict.fromkeys(n for _, n in pairs))
    msgs = probe(names)
    bad = []
    for n in names:
        if n not in msgs:
            bad.append(f"{n}: does not resolve")
            continue
        m = re.search(r"\[([^\]]*)\]", msgs[n])
        axioms = {a.strip() for a in m.group(1).split(",")} if m else set()
        if not axioms <= ALLOWED:
            bad.append(f"{n}: {sorted(axioms - ALLOWED)}")
    if bad:
        print("field map pins: FAILED", file=sys.stderr)
        for b in bad:
            print("  " + b, file=sys.stderr)
        return 1
    with open(OUT, "w", encoding="utf-8") as fh:
        for imp in IMPORTS:
            fh.write(f"import {imp}\n")
        fh.write("\n/-!\n# Axiom audit of `docs/field-map.md`\n\n"
                 "Generated by `scripts/field_map_pins.py`; do not edit by hand.  Every declaration\n"
                 "named in the field map is pinned to an axiom set contained in\n"
                 "`[propext, Classical.choice, Quot.sound]`.\n-/\n")
        leaf_of = {}
        for leaf, n in pairs:
            leaf_of.setdefault(n, leaf)
        for n in names:
            fh.write(f"\n-- {leaf_of[n]}\n/-- info: {msgs[n]} -/\n"
                     f"#guard_msgs (whitespace := lax) in\n#print axioms {n}\n")
    print(f"field map pins: {len(names)} declarations from {len({l for l, _ in pairs})} leaves "
          f"written to {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
